from __future__ import annotations

import json
import subprocess
from pathlib import Path

import numpy as np


def write_json(path: Path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2, allow_nan=False) + "\n")


def run(args):
    result = subprocess.run([str(a) for a in args], capture_output=True, text=True)
    if result.returncode:
        raise ValueError(f"{args[0]} failed: {result.stderr[-4000:]}")
    return result.stdout


def probe(path: Path):
    raw = json.loads(run(["ffprobe", "-v", "error", "-show_streams", "-show_format", "-of", "json", path]))
    video = next(s for s in raw["streams"] if s["codec_type"] == "video")
    # Do not copy QuickTime location tags or unrelated private metadata to scene artifacts.
    return {
        "width": video["width"], "height": video["height"],
        "duration_s": float(raw["format"]["duration"]),
        "codec": video["codec_name"], "color_transfer": video.get("color_transfer"),
        "color_primaries": video.get("color_primaries"),
        "time_base": video["time_base"],
        "streams": [{"type": s["codec_type"], "tag": s.get("codec_tag_string")} for s in raw["streams"]],
        "recorded_pose_depth": False,
        "pose_depth_note": "No supported RGB-D manifest supplied; QuickTime mebx tracks are not assumed to be ARKit poses or depth.",
    }


def timestamps(path: Path):
    # -show_entries frame alone still emits Dolby Vision side data; explicitly suppress it.
    raw = json.loads(run(["ffprobe", "-v", "error", "-select_streams", "v:0", "-show_frames",
        "-show_entries", "frame=best_effort_timestamp_time,duration_time:frame_side_data=", "-of", "json", path]))
    times = np.array([float(f["best_effort_timestamp_time"]) for f in raw["frames"]])
    if len(times) < 2 or not np.all(np.isfinite(times)) or np.any(np.diff(times) <= 0):
        raise ValueError("Video must contain strictly increasing presentation timestamps")
    return times - times[0]


def prepare(source: Path, output: Path, width=960):
    if output.exists():
        raise FileExistsError(f"Refusing to replace scene directory: {output}")
    info = probe(source)
    times = timestamps(source)
    output.mkdir(parents=True)
    (output / "rgb").mkdir()
    hdr = info["color_transfer"] == "arib-std-b67"
    if info["color_transfer"] == "smpte2084":
        raise ValueError("PQ footage requires a PQ viewing transform; this path implements HLG only")
    color = ""
    if hdr:
        from .color import write_hlg_lut
        lut = output / "hlg_to_sdr.cube"
        write_hlg_lut(lut)
        # Quoted filter paths are escaped for FFmpeg, never interpreted by a shell.
        escaped = str(lut.resolve()).replace("\\", "\\\\").replace("'", "'\\''").replace(":", "\\:")
        color = f"scale=in_color_matrix=bt2020:out_color_matrix=bt2020,format=rgb48le,lut3d=file='{escaped}':interp=tetrahedral,"
    run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-i", source, "-map", "0:v:0", "-an",
         "-vf", f"{color}scale={width}:-2,format=yuvj420p", "-fps_mode", "passthrough", "-q:v", "2",
         "-start_number", "0", output / "rgb/%06d.jpg"])
    files = sorted((output / "rgb").glob("*.jpg"))
    if len(files) != len(times):
        raise ValueError(f"Decoded frames {len(files)} differ from timestamps {len(times)}")
    info.update({"source": str(source.resolve()), "frame_count": len(times),
                 "variable_frame_rate": bool(np.ptp(np.diff(times)) > .0001),
                 "timestamp_min_step_s": float(np.min(np.diff(times))),
                 "timestamp_max_step_s": float(np.max(np.diff(times))),
                 "analysis_width": width, "tone_mapping": "BT.2100 inverse HLG OETF → linear BT.709 → fixed Hable (exposure 8) → sRGB; Dolby Vision RPU not applied" if hdr else "none"})
    write_json(output / "source.json", info)
    write_json(output / "frames.json", [{"index": i, "timestamp_s": float(t), "rgb": f"rgb/{i:06d}.jpg"} for i, t in enumerate(times)])
    return info


def encode_vfr(scene: Path, frame_dir: Path, target: Path):
    frames = json.loads((scene / "frames.json").read_text())
    source = json.loads((scene / "source.json").read_text())
    # Relative filenames generated by this program contain no user-controlled quoting.
    lines = ["ffconcat version 1.0"]
    for i, f in enumerate(frames):
        # A terminal copy gets one 600-Hz tick, so the last true frame holds
        # through the source's exact end time rather than losing its duration.
        end = frames[i+1]["timestamp_s"] if i + 1 < len(frames) else source["duration_s"]-1/600
        if end <= f["timestamp_s"]:
            raise ValueError("Final source duration must exceed the final PTS by at least one 600-Hz tick")
        lines.extend([f"file {frame_dir.name}/{i:06d}.png", "option framerate 600", f"duration {end-f['timestamp_s']:.9f}"])
    lines.append(f"file {frame_dir.name}/{len(frames)-1:06d}.png")
    lines.append("option framerate 600")
    concat = scene / f"{frame_dir.name}.ffconcat"
    concat.write_text("\n".join(lines) + "\n")
    run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-safe", "0", "-i", concat,
         "-an", "-c:v", "libx264", "-preset", "fast", "-crf", "18", "-bf", "0", "-pix_fmt", "yuv420p",
         "-fps_mode", "vfr", "-enc_time_base", "1:600", "-t", source["duration_s"], "-movflags", "+faststart", target])
